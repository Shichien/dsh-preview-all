/** Decode a base64 fixture into the bytes the decoder will consume. */
function bytes(base64) {
  return new Uint8Array(Buffer.from(base64, 'base64'))
}

/** The 200 KB repetitive text the large fixtures were produced from. */
function makeText(size) {
  const parts = []
  let length = 0
  let index = 0
  while (length < size) {
    const line = `line ${String(index).padStart(6, '0')}: the quick brown fox jumps over the lazy dog 0123456789\n`
    parts.push(line)
    length += line.length
    index += 1
  }
  return new TextEncoder().encode(parts.join('').slice(0, size))
}

/** The same deterministic pseudo-random bytes the random fixture was produced from. */
function makeRandom(size) {
  const out = new Uint8Array(size)
  let state = 2463534242
  for (let i = 0; i < size; i += 1) {
    state ^= (state << 13) >>> 0
    state >>>= 0
    state ^= state >>> 17
    state ^= (state << 5) >>> 0
    state >>>= 0
    out[i] = state & 0xff
  }
  return out
}

