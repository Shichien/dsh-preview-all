test('xz decodes a short literal stream', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_HELLO)), HELLO_XZ)
})

test('xz decodes the same text at presets 1, 6 and 9', () => {
  for (const fixture of [XZ_TEXT_P1, XZ_TEXT_P6, XZ_TEXT_P9]) {
    assert.deepEqual(decompressAll('xz', bytes(fixture)), TEXT)
  }
})

test('xz decodes an x86 BCJ filtered stream', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_TEXT_X86)), TEXT)
})

test('xz reverses the BCJ filter over opcode-dense data', () => {
  // Short match distances inside a BCJ stream exercise the shared
  // short-distance probability tree; getting its base offset wrong corrupts
  // every match that follows.
  assert.deepEqual(decompressAll('xz', bytes(XZ_BCJ)), bytes(XZ_BCJ_DATA))
})

test('xz decodes a delta filtered stream', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_TEXT_DELTA)), TEXT)
})

test('xz decodes incompressible input', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_RANDOM)), RANDOM)
})

test('xz decodes concatenated streams as one output', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_SPLIT)), TEXT)
})

test('xz decodes several blocks inside one stream', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_MULTI_BLOCK)), bytes(XZ_MULTI_BLOCK_DATA))
})

test('the output cap is enforced before a too-large result is produced', () => {
  for (const [format, fixture] of [
    ['bzip2', BZ2_TEXT],
    ['bzip2', BZ2_HELLO],
    ['xz', XZ_TEXT_P6],
    ['xz', XZ_HELLO],
  ]) {
    assertFails(() => decompressAll(format, bytes(fixture), { maxOutputBytes: 4 }), 'too-large')
  }
})

test('a generous output cap does not disturb a normal decode', () => {
  assert.deepEqual(decompressAll('xz', bytes(XZ_HELLO), { maxOutputBytes: 1024 }), HELLO_XZ)
  assert.deepEqual(decompressAll('bzip2', bytes(BZ2_HELLO), { maxOutputBytes: 1024 }), HELLO_BZIP2)
})

test('truncated streams are rejected as invalid', () => {
  for (const [format, fixture] of [
    ['bzip2', BZ2_HELLO],
    ['bzip2', BZ2_TEXT],
    ['xz', XZ_HELLO],
    ['xz', XZ_TEXT_P6],
  ]) {
    const stream = bytes(fixture)
    assertFails(() => decompressAll(format, stream.subarray(0, stream.length - 6)), 'invalid')
  }
})

test('a corrupted byte is rejected instead of yielding wrong output', () => {
  for (const [format, fixture] of [
    ['bzip2', BZ2_HELLO],
    ['bzip2', BZ2_TEXT],
    ['bzip2', BZ2_TEXT_SPLIT],
    ['xz', XZ_HELLO],
    ['xz', XZ_TEXT_P1],
    ['xz', XZ_TEXT_X86],
    ['xz', XZ_TEXT_DELTA],
    ['xz', XZ_RANDOM],
  ]) {
    const stream = bytes(fixture)
    assertFails(() => decompressAll(format, corruptMiddle(stream)), 'invalid')
  }
})

test('empty and nonsense input is invalid rather than silently empty', () => {
  assertFails(() => decompressAll('bzip2', new Uint8Array(0)), 'invalid')
  assertFails(() => decompressAll('xz', new Uint8Array(0)), 'invalid')
  assertFails(() => decompressAll('bzip2', bytes(XZ_HELLO)), 'invalid')
  assertFails(() => decompressAll('xz', bytes(BZ2_HELLO)), 'invalid')
})

test('an unknown format is unsupported', () => {
  assertFails(() => decompressAll('gzip', bytes(BZ2_HELLO)), 'unsupported')
})

test('an xz check type this decoder cannot verify is unsupported', () => {
  const stream = bytes(XZ_HELLO)
  stream[7] = 0x0a
  writeU32le(stream, 8, crc32(stream, 6, 8))
  assertFails(() => decompressAll('xz', stream), 'unsupported')
})

test('an xz filter this decoder does not implement is unsupported', () => {
  const stream = bytes(XZ_HELLO)
  const filterId = 14
  assert.equal(stream[filterId], 0x21, 'fixture should start with an LZMA2 filter')
  stream[filterId] = 0x07
  writeU32le(stream, 20, crc32(stream, 12, 20))
  assertFails(() => decompressAll('xz', stream), 'unsupported')
})

test('a randomised bzip2 block is unsupported rather than silently wrong', () => {
  const stream = bytes(BZ2_HELLO)
  stream[14] |= 0x80
  assertFails(() => decompressAll('bzip2', stream), 'unsupported')
})


test('sniffCompression recognises the magics it knows', () => {
  assert.equal(sniffCompression(Uint8Array.of(0x1f, 0x8b, 0x08, 0x00)), 'gzip')
  assert.equal(sniffCompression(Uint8Array.of(0x42, 0x5a, 0x68, 0x39)), 'bzip2')
  assert.equal(sniffCompression(Uint8Array.of(0xfd, 0x37, 0x7a, 0x58, 0x5a, 0x00)), 'xz')
  assert.equal(sniffCompression(Uint8Array.of(0x28, 0xb5, 0x2f, 0xfd)), 'zstd')
  assert.equal(sniffCompression(Uint8Array.of(0x50, 0x2a, 0x4d, 0x18)), 'zstd')
  assert.equal(sniffCompression(bytes(BZ2_TEXT)), 'bzip2')
  assert.equal(sniffCompression(bytes(XZ_TEXT_P6)), 'xz')
})

test('sniffCompression stays silent when it cannot tell', () => {
  assert.equal(sniffCompression(new Uint8Array(0)), undefined)
  assert.equal(sniffCompression(Uint8Array.of(0x00)), undefined)
  assert.equal(sniffCompression(new TextEncoder().encode('plain text file\n')), undefined)
})
