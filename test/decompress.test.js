/** Assert a decode failure carries the expected DecompressError code. */
function assertFails(run, code) {
  assert.throws(run, (error) => {
    assert.ok(error instanceof DecompressError, `expected a DecompressError, got ${error}`)
    assert.equal(error.code, code)
    return true
  })
}

/** Flip one byte in the middle of a stream so the payload is corrupt but the framing is not. */
function corruptMiddle(stream) {
  const copy = stream.slice()
  copy[copy.length >> 1] ^= 0xff
  return copy
}

/** Reflected CRC-32, used to repair container checksums after a test rewrites a header field. */
const CRC32_TABLE = (() => {
  const table = new Uint32Array(256)
  for (let i = 0; i < 256; i += 1) {
    let value = i
    for (let bit = 0; bit < 8; bit += 1) {
      value = (value & 1) !== 0 ? ((value >>> 1) ^ 0xedb88320) >>> 0 : (value >>> 1) >>> 0
    }
    table[i] = value >>> 0
  }
  return table
})()

function crc32(buffer, start = 0, end = buffer.length) {
  let crc = 0xffffffff
  for (let i = start; i < end; i += 1) {
    crc = ((crc >>> 8) ^ CRC32_TABLE[(crc ^ buffer[i]) & 0xff]) >>> 0
  }
  return (crc ^ 0xffffffff) >>> 0
}

function writeU32le(buffer, offset, value) {
  buffer[offset] = value & 0xff
  buffer[offset + 1] = (value >>> 8) & 0xff
  buffer[offset + 2] = (value >>> 16) & 0xff
  buffer[offset + 3] = (value >>> 24) & 0xff
}


